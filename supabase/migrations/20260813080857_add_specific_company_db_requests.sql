create or replace function public.oasis_list_admin_specific_company_db_requests(
    p_current_user_id text,
    p_statuses text[] default null,
    p_limit integer default 200
)
returns table (
    request_id uuid,
    requested_user_id text,
    requested_user_name text,
    company_name text,
    business_no text,
    business_type text,
    industry_name text,
    address text,
    masked_mobile_phone text,
    landline_phone text,
    has_mobile_phone boolean,
    has_landline_phone boolean,
    status text,
    decision_reason text,
    requested_at timestamptz,
    decided_at timestamptz
)
language plpgsql
stable
security invoker
set search_path = public, pg_temp
as $$
begin
    if not public.oasis_sales_actor_is_admin(p_current_user_id) then
        raise exception using
            errcode = '42501',
            message = 'OASIS_SALES_ADMIN_REQUIRED';
    end if;

    return query
    select
        r.id,
        r.requested_user_id,
        coalesce(u.name, r.requested_user_id),
        coalesce(nullif(btrim(c.company_name), ''), '업체명 미확인'),
        r.business_no,
        case
            when public.oasis_is_stock_company(c.company_name)
                then 'corporate'
            else 'individual'
        end,
        coalesce(c.industry_name, ''),
        coalesce(c.address, ''),
        case
            when length(regexp_replace(coalesce(c.mobile_phone, ''), '[^0-9]', '', 'g'))
                    between 10 and 11
                then substr(
                        regexp_replace(c.mobile_phone, '[^0-9]', '', 'g'),
                        1, 3
                     ) || '-****-' || right(
                        regexp_replace(c.mobile_phone, '[^0-9]', '', 'g'),
                        4
                     )
            when coalesce(c.has_mobile_phone, false)
                then '휴대폰 번호 보유'
            else ''
        end,
        coalesce(c.landline_phone, ''),
        coalesce(c.has_mobile_phone, false),
        coalesce(c.has_landline_phone, false),
        r.status,
        r.decision_reason,
        r.requested_at,
        r.decided_at
    from public.oasis_specific_company_db_requests r
    left join public.oasis_employment_contacts c
      on c.contact_key = r.source_contact_key
    left join public.oasis_users u
      on lower(u.user_id) = lower(r.requested_user_id)
    where coalesce(cardinality(p_statuses), 0) = 0
       or r.status = any(p_statuses)
    order by
        case when r.status = 'pending' then 0 else 1 end,
        r.requested_at,
        r.id
    limit greatest(1, least(coalesce(p_limit, 200), 1000));
end;
$$;

create or replace function public.oasis_admin_review_specific_company_db_request(
    p_current_user_id text,
    p_request_id uuid,
    p_action text,
    p_reason text default '',
    p_session_id text default null
)
returns table (
    success boolean,
    code text,
    message text,
    request_id uuid,
    status text,
    assignment_id uuid
)
language plpgsql
volatile
security invoker
set search_path = public, extensions, pg_temp
as $$
declare
    v_admin text := lower(btrim(coalesce(p_current_user_id, '')));
    v_action text := lower(btrim(coalesce(p_action, '')));
    v_reason text := left(btrim(coalesce(p_reason, '')), 500);
    v_request public.oasis_specific_company_db_requests%rowtype;
    v_contact public.oasis_employment_contacts%rowtype;
    v_claim record;
    v_payload jsonb;
    v_channel text;
begin
    if not public.oasis_sales_actor_is_admin(v_admin) then
        raise exception using
            errcode = '42501',
            message = 'OASIS_SALES_ADMIN_REQUIRED';
    end if;
    if p_request_id is null or v_action not in ('approve', 'reject') then
        return query select false, 'invalid_input',
            '처리할 신청과 작업을 확인해 주세요.',
            p_request_id, null::text, null::uuid;
        return;
    end if;
    if v_action = 'reject' and v_reason = '' then
        return query select false, 'reason_required',
            '반려 사유를 입력해 주세요.',
            p_request_id, null::text, null::uuid;
        return;
    end if;

    perform pg_advisory_xact_lock(
        hashtextextended('oasis-specific-db-request:' || p_request_id::text, 0)
    );
    select r.* into v_request
    from public.oasis_specific_company_db_requests r
    where r.id = p_request_id
    for update;

    if v_request.id is null then
        return query select false, 'not_found',
            '개별 DB 신청을 찾지 못했습니다.',
            p_request_id, null::text, null::uuid;
        return;
    end if;
    if v_request.status <> 'pending' then
        return query select false, 'already_resolved',
            '이미 처리가 끝난 신청입니다.',
            v_request.id, v_request.status, v_request.assignment_id;
        return;
    end if;

    if v_action = 'reject' then
        update public.oasis_specific_company_db_requests r
        set
            status = 'rejected',
            decision_reason = v_reason,
            decided_by_user_id = v_admin,
            decided_at = now(),
            updated_at = now()
        where r.id = v_request.id;
        insert into public.oasis_specific_company_db_request_events (
            request_id, actor_user_id, action, reason
        ) values (v_request.id, v_admin, 'rejected', v_reason);
        return query select true, 'rejected',
            '개별 DB 신청을 반려했습니다.',
            v_request.id, 'rejected', null::uuid;
        return;
    end if;

    select c.* into v_contact
    from public.oasis_employment_contacts c
    where c.contact_key = v_request.source_contact_key
      and c.business_no = v_request.business_no;

    if v_contact.contact_key is null
       or not (
          coalesce(v_contact.has_mobile_phone, false)
          or coalesce(v_contact.has_landline_phone, false)
       ) then
        return query select false, 'contact_unavailable',
            '승인 시점에 유효한 전화번호 DB를 확인하지 못했습니다.',
            v_request.id, v_request.status, null::uuid;
        return;
    end if;

    v_channel := case
        when coalesce(v_contact.has_mobile_phone, false) then 'mobile'
        else 'landline'
    end;
    v_payload := jsonb_build_object(
        'company_uid', v_request.company_uid,
        'business_no', v_request.business_no,
        'company_name', v_contact.company_name,
        'address', v_contact.address,
        'industry_name', v_contact.industry_name,
        'employee_count', coalesce(v_contact.current_employee_count, 0),
        'new_employee_count', greatest(coalesce(v_contact.employee_growth, 0), 0),
        'mobile_phone', v_contact.mobile_phone,
        'landline_phone', v_contact.landline_phone,
        'phone', coalesce(
            nullif(v_contact.mobile_phone, ''),
            nullif(v_contact.landline_phone, ''),
            ''
        ),
        'source', coalesce(nullif(v_contact.source_type, ''), 'specific_db_request'),
        'source_key', coalesce(
            nullif(v_contact.source_record_key, ''),
            v_contact.contact_key
        ),
        'source_data', jsonb_build_object(
            'allocation_channel', v_channel,
            'discovery_type', 'specific_request',
            'specific_db_request_id', v_request.id,
            'contact_key', v_contact.contact_key
        )
    );

    select * into v_claim
    from public.oasis_claim_and_save_company_sales_assignment(
        v_request.requested_user_id,
        v_request.company_uid,
