begin;

-- 사업자등록번호로 정확히 조회한 업체의 개별 배정 신청을 관리한다.
-- 원문 휴대전화는 신청 테이블과 사용자 조회 결과에 저장하거나 반환하지 않는다.
create table if not exists public.oasis_specific_company_db_requests (
    id uuid primary key default extensions.gen_random_uuid(),
    requested_user_id text not null,
    company_uid text not null,
    business_no text not null,
    source_contact_key text not null,
    status text not null default 'pending',
    decision_reason text not null default '',
    decided_by_user_id text,
    assignment_id uuid references public.oasis_company_sales_assignments(id)
        on delete set null,
    prospect_id uuid references public.oasis_prospect_companies(id)
        on delete set null,
    requested_at timestamptz not null default now(),
    decided_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint oasis_specific_company_db_requests_uid_check
        check (public.oasis_is_valid_company_uid(company_uid)),
    constraint oasis_specific_company_db_requests_business_no_check
        check (business_no ~ '^[0-9]{10}$'),
    constraint oasis_specific_company_db_requests_status_check
        check (status in ('pending', 'approved', 'rejected', 'cancelled'))
);

create unique index if not exists
    idx_oasis_specific_company_db_requests_one_pending_company
on public.oasis_specific_company_db_requests (company_uid)
where status = 'pending';

create index if not exists idx_oasis_specific_company_db_requests_user
    on public.oasis_specific_company_db_requests (
        requested_user_id, requested_at desc, id
    );

create index if not exists idx_oasis_specific_company_db_requests_admin
    on public.oasis_specific_company_db_requests (status, requested_at, id);

create index if not exists idx_oasis_employment_contacts_business_no_exact
    on public.oasis_employment_contacts (business_no)
    where business_no ~ '^[0-9]{10}$';

create table if not exists public.oasis_specific_company_db_request_events (
    id bigint generated by default as identity primary key,
    request_id uuid not null
        references public.oasis_specific_company_db_requests(id)
        on delete cascade,
    actor_user_id text not null,
    action text not null,
    reason text not null default '',
    created_at timestamptz not null default now(),
    constraint oasis_specific_company_db_request_events_action_check
        check (action in ('requested', 'approved', 'rejected', 'cancelled'))
);

create index if not exists idx_oasis_specific_company_db_request_events_request
    on public.oasis_specific_company_db_request_events (
        request_id, created_at, id
    );

alter table public.oasis_specific_company_db_requests
    enable row level security;
alter table public.oasis_specific_company_db_request_events
    enable row level security;

revoke all on table public.oasis_specific_company_db_requests
    from public, anon, authenticated;
revoke all on table public.oasis_specific_company_db_request_events
    from public, anon, authenticated;
grant select, insert, update on table public.oasis_specific_company_db_requests
    to service_role;
grant select, insert on table public.oasis_specific_company_db_request_events
    to service_role;

create or replace function public.oasis_search_company_db_by_business_no(
    p_current_user_id text,
    p_business_no text
)
returns table (
    found boolean,
    code text,
    message text,
    company_uid text,
    company_name text,
    business_no text,
    business_type text,
    industry_name text,
    address text,
    masked_mobile_phone text,
    landline_phone text,
    has_mobile_phone boolean,
    has_landline_phone boolean,
    requestable boolean,
    request_status text,
    request_id uuid
)
language plpgsql
stable
security invoker
set search_path = public, pg_temp
as $$
declare
    v_actor text := lower(btrim(coalesce(p_current_user_id, '')));
    v_business_no text := public.oasis_sales_digits(p_business_no);
    v_contact public.oasis_employment_contacts%rowtype;
    v_assignment public.oasis_company_sales_assignments%rowtype;
    v_request public.oasis_specific_company_db_requests%rowtype;
    v_uid text;
    v_mobile_digits text;
    v_request_status text := 'available';
    v_requestable boolean := false;
begin
    if not public.oasis_sales_actor_is_active(v_actor) then
        raise exception using
            errcode = '42501',
            message = 'OASIS_SALES_USER_NOT_AUTHORIZED';
    end if;
    if length(v_business_no) <> 10 then
        return query select
            false, 'invalid_input',
            '사업자등록번호 10자리를 입력해 주세요.',
            null::text, null::text, null::text, null::text,
            null::text, null::text, null::text, null::text,
            false, false, false, 'invalid', null::uuid;
        return;
    end if;

    select c.* into v_contact
    from public.oasis_employment_contacts c
    where c.business_no = v_business_no
      and (
          coalesce(c.has_mobile_phone, false)
          or coalesce(c.has_landline_phone, false)
      )
    order by
        coalesce(c.has_mobile_phone, false) desc,
        coalesce(c.has_landline_phone, false) desc,
        c.phone_checked_at desc nulls last,
        c.checked_at desc nulls last,
        c.contact_key
    limit 1;

    if v_contact.contact_key is null then
        return query select
            false, 'not_found',
            '해당 사업자등록번호로 신청 가능한 전화번호 DB를 찾지 못했습니다.',
            null::text, null::text, v_business_no, null::text,
            null::text, null::text, null::text, null::text,
            false, false, false, 'not_found', null::uuid;
        return;
    end if;

    v_uid := 'business:' || v_business_no;
    v_mobile_digits := regexp_replace(
        coalesce(v_contact.mobile_phone, ''), '[^0-9]', '', 'g'
    );

    select a.* into v_assignment
    from public.oasis_company_sales_assignments a
    where a.company_uid = v_uid;

    select r.* into v_request
    from public.oasis_specific_company_db_requests r
    where r.company_uid = v_uid
      and r.status = 'pending'
    order by r.requested_at, r.id
    limit 1;

    if v_assignment.company_uid is not null
       and v_assignment.assigned_user_id = v_actor
       and v_assignment.status <> 'unassigned' then
        v_request_status := 'already_owned';
    elsif v_assignment.company_uid is not null
       and not (
           v_assignment.status = 'unassigned'
           and v_assignment.assigned_user_id is null
           and coalesce(v_assignment.permanently_excluded, false) is false
           and coalesce(v_assignment.migration_conflict, false) is false
       ) then
        v_request_status := case
            when coalesce(v_assignment.permanently_excluded, false)
                then 'permanently_excluded'
            else 'unavailable'
        end;
    elsif v_request.id is not null then
        v_request_status := case
            when v_request.requested_user_id = v_actor then 'pending_own'
            else 'pending_other'
        end;
    else
        v_request_status := 'available';
        v_requestable := true;
    end if;

    return query select
        true,
        'found',
        case v_request_status
            when 'available' then '신청 가능한 업체입니다.'
            when 'pending_own' then '관리자 승인 대기 중인 업체입니다.'
            when 'pending_other' then '현재 다른 신청을 검토 중인 업체입니다.'
            when 'already_owned' then '이미 내 DB에 배정된 업체입니다.'
            when 'permanently_excluded' then '영구 제외된 업체입니다.'
            else '현재 신청할 수 없는 업체입니다.'
        end,
        v_uid,
        coalesce(nullif(btrim(v_contact.company_name), ''), '업체명 미확인'),
        v_business_no,
        case
            when public.oasis_is_stock_company(v_contact.company_name)
                then 'corporate'
            else 'individual'
        end,
        coalesce(v_contact.industry_name, ''),
        coalesce(v_contact.address, ''),
        case
            when length(v_mobile_digits) between 10 and 11
                then substr(v_mobile_digits, 1, 3)
                     || '-****-' || right(v_mobile_digits, 4)
            when coalesce(v_contact.has_mobile_phone, false)
                then '휴대폰 번호 보유'
            else ''
        end,
        coalesce(v_contact.landline_phone, ''),
        coalesce(v_contact.has_mobile_phone, false),
        coalesce(v_contact.has_landline_phone, false),
        v_requestable,
        v_request_status,
        case
            when v_request.requested_user_id = v_actor then v_request.id
            else null::uuid
        end;
end;
$$;

create or replace function public.oasis_submit_specific_company_db_request(
    p_current_user_id text,
    p_business_no text,
    p_session_id text default null
)
returns table (
    success boolean,
    code text,
    message text,
    request_id uuid,
    status text
)
language plpgsql
volatile
security invoker
set search_path = public, extensions, pg_temp
as $$
declare
    v_actor text := lower(btrim(coalesce(p_current_user_id, '')));
    v_business_no text := public.oasis_sales_digits(p_business_no);
    v_contact public.oasis_employment_contacts%rowtype;
    v_assignment public.oasis_company_sales_assignments%rowtype;
    v_existing public.oasis_specific_company_db_requests%rowtype;
    v_saved public.oasis_specific_company_db_requests%rowtype;
    v_uid text;
begin
    if not public.oasis_sales_actor_is_active(v_actor) then
        raise exception using
            errcode = '42501',
            message = 'OASIS_SALES_USER_NOT_AUTHORIZED';
    end if;
    if length(v_business_no) <> 10 then
        return query select false, 'invalid_input',
            '사업자등록번호 10자리를 입력해 주세요.',
            null::uuid, null::text;
        return;
    end if;

    v_uid := 'business:' || v_business_no;
    perform pg_advisory_xact_lock(
        hashtextextended('oasis-specific-db:' || v_uid, 0)
    );

    select c.* into v_contact
    from public.oasis_employment_contacts c
    where c.business_no = v_business_no
      and (
          coalesce(c.has_mobile_phone, false)
          or coalesce(c.has_landline_phone, false)
      )
    order by
        coalesce(c.has_mobile_phone, false) desc,
        coalesce(c.has_landline_phone, false) desc,
        c.phone_checked_at desc nulls last,
        c.checked_at desc nulls last,
        c.contact_key
    limit 1;

    if v_contact.contact_key is null then
        return query select false, 'not_found',
            '해당 사업자등록번호로 신청 가능한 전화번호 DB를 찾지 못했습니다.',
            null::uuid, null::text;
        return;
    end if;

    select a.* into v_assignment
    from public.oasis_company_sales_assignments a
    where a.company_uid = v_uid
    for update;

    if v_assignment.company_uid is not null
       and not (
           v_assignment.status = 'unassigned'
           and v_assignment.assigned_user_id is null
           and coalesce(v_assignment.permanently_excluded, false) is false
           and coalesce(v_assignment.migration_conflict, false) is false
       ) then
        return query select false, 'unavailable',
            case
                when v_assignment.assigned_user_id = v_actor
                    then '이미 내 DB에 배정된 업체입니다.'
                else '현재 신청할 수 없는 업체입니다.'
            end,
            null::uuid, null::text;
        return;
    end if;

    select r.* into v_existing
    from public.oasis_specific_company_db_requests r
    where r.company_uid = v_uid
      and r.status = 'pending'
    order by r.requested_at, r.id
    limit 1
    for update;

    if v_existing.id is not null then
        return query select
            v_existing.requested_user_id = v_actor,
            case when v_existing.requested_user_id = v_actor
                then 'already_requested' else 'pending_other' end,
            case when v_existing.requested_user_id = v_actor
                then '이미 관리자 승인 대기 중인 업체입니다.'
                else '현재 다른 신청을 검토 중인 업체입니다.' end,
            case when v_existing.requested_user_id = v_actor
                then v_existing.id else null::uuid end,
            v_existing.status;
        return;
    end if;

    insert into public.oasis_specific_company_db_requests (
        requested_user_id,
        company_uid,
        business_no,
        source_contact_key
    ) values (
        v_actor,
        v_uid,
        v_business_no,
        v_contact.contact_key
    ) returning * into v_saved;

    insert into public.oasis_specific_company_db_request_events (
        request_id, actor_user_id, action, reason
    ) values (
        v_saved.id, v_actor, 'requested',
        left(coalesce(p_session_id, ''), 500)
    );

    return query select true, 'requested',
        'DB 신청을 접수했습니다. 관리자 승인 후 내 DB에 배정됩니다.',
        v_saved.id, v_saved.status;
end;
$$;

